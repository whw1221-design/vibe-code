create table if not exists public.users (
  uid integer generated by default as identity primary key,
  uname text not null,
  email text not null,
  password text not null,
  constraint users_email_key unique (email),
  constraint users_email_lowercase check (email = lower(email))
);

create table if not exists public.products (
  pid integer generated by default as identity primary key,
  pname text not null,
  description text not null default '',
  price numeric(12, 2) not null default 0 check (price >= 0),
  qty integer not null default 0 check (qty >= 0)
);

create table if not exists public.orders (
  oid integer generated by default as identity primary key,
  uid integer not null,
  pid integer not null,
  order_date timestamptz not null default now(),
  constraint orders_uid_fkey foreign key (uid)
    references public.users (uid) on delete cascade on update cascade,
  constraint orders_pid_fkey foreign key (pid)
    references public.products (pid) on delete cascade on update cascade
);

create index if not exists idx_orders_uid on public.orders (uid);
create index if not exists idx_orders_pid on public.orders (pid);
create index if not exists idx_orders_order_date on public.orders (order_date desc);

-- The Express backend uses the service_role key, which bypasses RLS.
-- Enabling RLS with no public policies keeps anon/authenticated clients out.
alter table public.users enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;

revoke all on table public.users from anon, authenticated;
revoke all on table public.products from anon, authenticated;
revoke all on table public.orders from anon, authenticated;

grant all on table public.users, public.products, public.orders to service_role;
grant usage, select on all sequences in schema public to service_role;

